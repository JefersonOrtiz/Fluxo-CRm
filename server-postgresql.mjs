import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { join, extname, resolve, sep } from 'node:path';
import { Pool } from 'pg';

const root = process.cwd();
const port = Number(process.env.PORT || 3000);
if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL não configurada');
const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 10, connectionTimeoutMillis: 10000, idleTimeoutMillis: 30000 });
pool.on('error', error => console.error('Erro em conexão ociosa do PostgreSQL:', error));

// Inicialização idempotente. Não remove nem substitui tabelas existentes.
await pool.query(`
 CREATE TABLE IF NOT EXISTS contacts (
   id TEXT PRIMARY KEY, name TEXT NOT NULL, company TEXT, phone TEXT, email TEXT,
   stage TEXT NOT NULL DEFAULT 'Novo lead', value_cents INTEGER NOT NULL DEFAULT 0,
   notes TEXT NOT NULL DEFAULT '', ai_enabled INTEGER NOT NULL DEFAULT 1,
   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
   updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
 );
 CREATE TABLE IF NOT EXISTS tags (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name TEXT NOT NULL UNIQUE
 );
 CREATE TABLE IF NOT EXISTS contact_tags (
   contact_id TEXT NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
   tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
   PRIMARY KEY (contact_id, tag_id)
 );
 CREATE TABLE IF NOT EXISTS messages (
   id TEXT PRIMARY KEY,
   contact_id TEXT NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
   sender TEXT NOT NULL CHECK (sender IN ('client', 'agent', 'ai')),
   body TEXT NOT NULL,
   sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
   status TEXT NOT NULL DEFAULT 'sent'
 );
 CREATE TABLE IF NOT EXISTS events (
   id TEXT PRIMARY KEY,
   contact_id TEXT REFERENCES contacts(id) ON DELETE SET NULL,
   title TEXT NOT NULL, starts_at TEXT NOT NULL,
   type TEXT NOT NULL DEFAULT 'reuniao',
   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
 );
 CREATE INDEX IF NOT EXISTS idx_messages_contact_date ON messages(contact_id, sent_at);
 CREATE INDEX IF NOT EXISTS idx_events_start ON events(starts_at);
`);
console.log('PostgreSQL conectado; esquema verificado');

const json = (res, status, body) => {
  res.writeHead(status, { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' });
  res.end(JSON.stringify(body));
};
const readBody = req => new Promise((resolveBody, reject) => {
  const chunks = [];
  let size = 0;
  req.on('data', chunk => {
    size += chunk.length;
    if (size > 1_000_000) {
      reject(Object.assign(new Error('Payload muito grande'), { status: 413 }));
      req.destroy();
      return;
    }
    chunks.push(chunk);
  });
  req.on('end', () => {
    try {
      const data = chunks.length ? JSON.parse(Buffer.concat(chunks).toString('utf8')) : {};
      if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error('Objeto JSON esperado');
      resolveBody(data);
    } catch {
      reject(Object.assign(new Error('JSON inválido'), { status: 400 }));
    }
  });
  req.on('error', reject);
});
const mime = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };
const allowedFields = ['name', 'company', 'phone', 'email', 'stage', 'value_cents', 'notes', 'ai_enabled'];
const legacyFiles = {
  'js/app.js': 'js/app.js.txt',
  'js/ai.js': 'js/ai.js.txt',
  'js/data.js': 'js/data.js.txt',
  'css/style.css': 'css/style.css.css'
};
const publicPrefixes = ['css/', 'js/', 'assets/', 'images/', 'img/', 'fonts/'];
const publicRootFiles = new Set(['index.html', 'favicon.ico', 'manifest.json', 'robots.txt']);

const server = createServer(async (req, res) => {
  try {
    const url = new URL(req.url, 'http://localhost');
    const pathname = url.pathname;
    if (pathname === '/api/health' && req.method === 'GET') {
      await pool.query('SELECT 1');
      return json(res, 200, { ok: true, database: 'postgresql' });
    }
    // IMPORTANTE: rotas sem autenticação. NÃO exponha publicamente antes de implementar auth.
    if (pathname === '/api/contacts' && req.method === 'GET') {
      const result = await pool.query('SELECT * FROM contacts ORDER BY updated_at DESC');
      return json(res, 200, result.rows);
    }
    if (pathname === '/api/contacts' && req.method === 'POST') {
      const item = await readBody(req);
      if (typeof item.id !== 'string' || !item.id.trim() || typeof item.name !== 'string' || !item.name.trim()) {
        return json(res, 400, { error: 'id e name são obrigatórios' });
      }
      const values = [item.id, item.name, item.company ?? '', item.phone ?? '', item.email ?? '', item.stage ?? 'Novo lead', item.value_cents ?? 0, item.notes ?? '', item.ai_enabled ?? 1];
      const result = await pool.query(`INSERT INTO contacts (id,name,company,phone,email,stage,value_cents,notes,ai_enabled)
        VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9) RETURNING *`, values);
      return json(res, 201, result.rows[0]);
    }
    const contactMatch = pathname.match(/^\/api\/contacts\/([^/]+)$/);
    if (contactMatch && req.method === 'PATCH') {
      const id = decodeURIComponent(contactMatch[1]);
      const patch = await readBody(req);
      const keys = Object.keys(patch).filter(key => allowedFields.includes(key));
      if (!keys.length) return json(res, 400, { error: 'Nenhum campo editável enviado' });
      if ('name' in patch && (typeof patch.name !== 'string' || !patch.name.trim())) return json(res, 400, { error: 'Nome inválido' });
      const values = keys.map(key => patch[key]);
      values.push(id);
      const set = keys.map((key, i) => `${key} = $${i + 1}`).join(', ');
      const result = await pool.query(`UPDATE contacts SET ${set}, updated_at = CURRENT_TIMESTAMP WHERE id = $${values.length} RETURNING *`, values);
      if (!result.rowCount) return json(res, 404, { error: 'Contato não encontrado' });
      return json(res, 200, result.rows[0]);
    }
    if (pathname === '/api/events' && req.method === 'GET') {
      const result = await pool.query('SELECT * FROM events ORDER BY starts_at');
      return json(res, 200, result.rows);
    }
    if (pathname.startsWith('/api/')) return json(res, 404, { error: 'Rota não encontrada' });
    if (req.method !== 'GET' && req.method !== 'HEAD') return json(res, 405, { error: 'Método não permitido' });

    // Servir somente recursos públicos conhecidos; nunca servir .env, código do servidor ou banco.
    let requested;
    try { requested = decodeURIComponent(pathname === '/' ? '/index.html' : pathname).replace(/^\/+/, ''); }
    catch { return json(res, 400, { error: 'Caminho inválido' }); }
    if (requested.includes('\\') || requested.split('/').some(part => part === '..' || part.startsWith('.'))) return json(res, 403, { error: 'Acesso negado' });
    if (!publicRootFiles.has(requested) && !publicPrefixes.some(prefix => requested.startsWith(prefix))) return json(res, 404, { error: 'Não encontrado' });
    let filePath = resolve(root, requested);
    if (!filePath.startsWith(root + sep)) return json(res, 403, { error: 'Acesso negado' });
    try {
      const content = await readFile(filePath);
      res.writeHead(200, { 'Content-Type': mime[extname(requested)] || 'application/octet-stream', 'X-Content-Type-Options': 'nosniff' });
      return res.end(req.method === 'HEAD' ? undefined : content);
    } catch (error) {
      if (error.code !== 'ENOENT' || !legacyFiles[requested]) throw error;
      const content = await readFile(resolve(root, legacyFiles[requested]));
      res.writeHead(200, { 'Content-Type': mime[extname(requested)] || 'application/octet-stream', 'X-Content-Type-Options': 'nosniff' });
      return res.end(req.method === 'HEAD' ? undefined : content);
    }
  } catch (error) {
    if (error.code === 'ENOENT') return json(res, 404, { error: 'Não encontrado' });
    if (error.code === '23505') return json(res, 409, { error: 'Registro duplicado' });
    if (error.code === '22P02' || error.code === '23502' || error.code === '23514' || error.code === '22003' || error.code === '23503') return json(res, 400, { error: 'Dados inválidos' });
    if (error.status === 400 || error.status === 413) return json(res, error.status, { error: error.message });
    console.error('Erro na requisição:', error);
    return json(res, 500, { error: 'Erro interno' });
  }
});
server.listen(port, '0.0.0.0', () => console.log(`Fluxo CRM ouvindo na porta ${port}`));
for (const signal of ['SIGTERM', 'SIGINT']) {
  process.on(signal, () => server.close(async () => { await pool.end(); process.exit(0); }));
}
